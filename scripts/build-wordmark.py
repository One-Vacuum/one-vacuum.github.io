"""Regenerate the ONE VACUUM wordmark (src/components/Logo.astro and public/images/logo.svg).

The letters are outlines of Archivo (SIL OFL) at wdth 125 / wght 640 with +60
tracking, shaped with HarfBuzz so kerning applies. The "O" is replaced by a
geometric ring (stroke 0.84 x the "I" stem) with a centre dot (0.2 x radius).

Setup (once):
    python3 -m venv .venv && .venv/bin/pip install fonttools uharfbuzz
    curl -L -o Archivo.ttf "https://github.com/google/fonts/raw/main/ofl/archivo/Archivo%5Bwdth,wght%5D.ttf"
Run from the repo root:
    .venv/bin/python scripts/build-wordmark.py Archivo.ttf

logo.png (1200x630 link preview) and the favicons are rendered from these
SVGs (browser screenshot, then ImageMagick resize); see CLAUDE.md → "Logo".
"""
import io
import sys

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WGHT, TRACKING, RING_STROKE, RING_GAP, DOT = 640, 60, 0.84, 28, 0.2
INK, ACCENT = '#111216', '#1F5BFF'

vf = TTFont(sys.argv[1])
buf = io.BytesIO()
instantiateVariableFont(vf, {'wdth': 125, 'wght': WGHT}).save(buf)
data = buf.getvalue()
font = TTFont(io.BytesIO(data))
gs, cmap, order = font.getGlyphSet(), font.getBestCmap(), font.getGlyphOrder()


def bounds(name):
    pen = BoundsPen(gs)
    gs[name].draw(pen)
    return pen.bounds


stem = (lambda b: b[2] - b[0])(bounds(cmap[ord('I')]))
o_name = cmap[ord('O')]
o_box = bounds(o_name)
o_lsb, o_rsb = o_box[0], font['hmtx'][o_name][0] - o_box[2]

# Ring: same height as the real O (overshoot included), perfectly round.
D = o_box[3] - o_box[1]
R, s = D / 2, stem * RING_STROKE
cx, cy = o_lsb + R, -(o_box[1] + R)

hbuf = hb.Buffer()
hbuf.add_str('NE VACUUM')
hbuf.guess_segment_properties()
hb.shape(hb.Font(hb.Face(data)), hbuf, {'kern': True, 'liga': False})

x = o_lsb + D + o_rsb + TRACKING + RING_GAP
letters = []
for info, pos in zip(hbuf.glyph_infos, hbuf.glyph_positions):
    pen = SVGPathPen(gs)
    gs[order[info.codepoint]].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, 0)))
    letters.append(pen.getCommands())
    x += pos.x_advance + TRACKING
last = order[hbuf.glyph_infos[-1].codepoint]
right = x - TRACKING - font['hmtx'][last][0] + bounds(last)[2]


def circle(r):
    return f'M{cx - r:.1f} {cy:.1f}a{r:.1f} {r:.1f} 0 1 0 {2 * r:.1f} 0a{r:.1f} {r:.1f} 0 1 0 {-2 * r:.1f} 0Z'


view_box = f'{o_lsb:.1f} {-o_box[3]:.1f} {right - o_lsb:.1f} {D:.1f}'
ring, letters_d = circle(R) + circle(R - s), ''.join(letters)
dot = f'cx="{cx:.1f}" cy="{cy:.1f}" r="{R * DOT:.1f}"'

with open('public/images/logo.svg', 'w') as f:
    f.write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" width="{(right - o_lsb) / 10:.1f}" height="{D / 10:.1f}">'
        f'<path fill="{INK}" fill-rule="evenodd" d="{ring}"/><circle {dot} fill="{ACCENT}"/>'
        f'<path fill="{INK}" d="{letters_d}"/></svg>'
    )

with open('src/components/Logo.astro', 'w') as f:
    f.write(f'''---
// One Vacuum wordmark. Generated by scripts/build-wordmark.py — regenerate
// rather than editing the paths. Letters and ring follow `currentColor`; the
// dot uses the brand accent.
interface Props {{
  class?: string;
  title?: string;
}}
const {{ class: className = '', title = 'One Vacuum' }} = Astro.props;
---

<svg viewBox="{view_box}" class={{className}} role="img" aria-label={{title}} xmlns="http://www.w3.org/2000/svg">
  <path fill="currentColor" fill-rule="evenodd" d="{ring}" />
  <circle {dot} class="fill-accent dark:fill-accent-light" />
  <path fill="currentColor" d="{letters_d}" />
</svg>
''')
print('wrote public/images/logo.svg and src/components/Logo.astro', view_box)
